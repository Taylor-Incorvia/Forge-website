/** Fast lookup for route params and pool cross-references. */
export const UNITS_BY_ID: ReadonlyMap<string, Unit> = new Map(UNITS.map((u) => [u.id, u]))

/** Multiplayer game-speed multiplier. "Faster" is the only speed anyone plays. */
const FASTER_MULTIPLIER = 1.4

/** Trim "48.0" to "48" without mangling integers like "20". */
function trimZeros(value: string): string {
  if (!value.includes('.')) return value
  return value.replace(/0+$/, '').replace(/\.$/, '')
}

/**
 * Catalog build time -> the number a player actually experiences.
 *
 * The single place this conversion happens. Rendering `buildTimeCatalog`
 * anywhere else would show a duration that never occurs in a real game.
 */
export function formatBuildTime(catalogSeconds: number): string {
  return `${trimZeros((catalogSeconds / FASTER_MULTIPLIER).toFixed(1))}s`
}

/** Catalog attack period -> real seconds between attacks at Faster. */
export function formatPeriod(catalogSeconds: number): string {
  return `${trimZeros((catalogSeconds / FASTER_MULTIPLIER).toFixed(2))}s`
}

/**
 * Catalog DPS expression -> the same expression at Faster.
 *
 * Scales every number in the string, which is safe because every number in a
 * DPS field is itself a DPS figure — including the conditional variants and the
 * increments in forms like "~12 base (+8 vs Armored)". Non-numeric values such
 * as "burst" pass through untouched.
 */
export function formatDps(catalogDps: string): string {
  return catalogDps.replace(/\d+(?:\.\d+)?/g, (match) =>
    trimZeros((Number(match) * FASTER_MULTIPLIER).toFixed(1)),
  )
}
